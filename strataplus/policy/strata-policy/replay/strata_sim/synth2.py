"""SYNTHETIC per-position (teacher-forced) traces in the strataplus.v1 sense (data_kind = "synthetic").

Everything produced here is SYNTHETIC: token streams y are generated by a toy process, MTP drafts/probabilities by a
toy latent-difficulty model. Lookup and pool proposals, instead, come from the PRODUCTION SuffixDrafter (ctypes)
run on those synthetic tokens. No number derived from these traces is a measurement of Strata.

Per request and per output position i (pos = i tokens already committed), with Dmax = 7:
  mtp_tok[i, j]  MTP draft j+1 (tokens predicted for y[i+j])        mtp_p[i, j]  top-1 prob,  mtp_ent[i, j] entropy
  mtp_acc[i]     LCP(mtp_tok[i], y[i:])                              (path-independent by construction, piano Q2/V1)
  lk_k, lk_m, lk_acc, lk_tok   SuffixDrafter (reset per request, prompt appended) proposal / match / LCP
  pl_k, pl_m, pl_acc, pl_tok   persistent pool drafter (never reset within a domain stream)
  agree[i] = LCP(mtp_tok[i], lk_tok[i]);  agree_pl[i] likewise for the pool
"""
from __future__ import annotations
import numpy as np
from .native import NativeSuffixDrafter

DMAX = 7
V = 6000


class Gen:
    def __init__(self, domain, seed):
        self.dom, self.rng = domain, np.random.default_rng(seed)
        r = self.rng
        z = 1.0 / np.arange(1, V + 1) ** 1.05
        self.zipf = z / z.sum()
        # shared phrase library across requests of the domain (what a cross-request pool can learn)
        nlib, lo, hi = {"code": (80, 6, 40), "chat": (60, 4, 14), "edit": (40, 6, 20), "session": (40, 6, 20)}[domain]
        self.lib = [self.free(int(r.integers(lo, hi))) for _ in range(nlib)]
        self.lib_w = 1.0 / np.arange(1, nlib + 1) ** 0.8
        self.lib_w /= self.lib_w.sum()
        self.session_file = None

    def free(self, n):
        return self.rng.choice(V, size=n, p=self.zipf).astype(np.int32)

    def geo(self, mean):
        return int(self.rng.geometric(1.0 / mean))

    def libseg(self):
        return self.lib[int(self.rng.choice(len(self.lib), p=self.lib_w))]

    def request(self, turn=0):
        """returns prompt tokens, y tokens, kind[y] in {0 free, 1 copy, 2 library, 3 segment start}"""
        r = self.rng
        y, kind = [], []

        def emit(seg, k):
            y.extend(seg.tolist()); kind.extend([3] + [k] * (len(seg) - 1) if k else [0] * len(seg))

        if self.dom == "code":
            prompt = self.free(int(r.integers(80, 500)))
            n = int(r.integers(120, 500))
            while len(y) < n:
                u = r.random()
                if u < 0.22 and len(y) > 20:
                    s = int(r.integers(0, len(y) - 5)); emit(np.array(y[s:s + self.geo(10)], np.int32), 1)
                elif u < 0.34:
                    s = int(r.integers(0, len(prompt) - 3)); emit(prompt[s:s + self.geo(5)], 1)
                elif u < 0.50:
                    emit(self.libseg(), 2)
                else:
                    emit(self.free(self.geo(12)), 0)
        elif self.dom == "chat":
            ctx = self.free(int(r.integers(0, 1200))) if r.random() < 0.4 else np.zeros(0, np.int32)
            prompt = np.concatenate([self.free(int(r.integers(20, 120))), ctx])
            n = int(r.integers(80, 450))
            while len(y) < n:
                u = r.random()
                if u < 0.07 and len(ctx) > 20:
                    s = int(r.integers(0, len(ctx) - 5)); emit(ctx[s:s + self.geo(12)], 1)
                elif u < 0.15:
                    emit(self.libseg(), 2)
                else:
                    emit(self.free(self.geo(15)), 0)
        else:   # edit / session: rewrite of a document with edit points
            if self.dom == "session":
                if self.session_file is None or turn == 0:
                    self.session_file = self.free(int(r.integers(600, 1500)))
                doc = self.session_file
                # the turn only sees an excerpt of the file (agent sends excerpts), outputs an edited region
                a = int(r.integers(0, max(1, len(doc) - 300))); b = min(len(doc), a + int(r.integers(150, 400)))
                ex = int(r.integers(a, max(a + 1, b - 60)))
                prompt = np.concatenate([self.free(int(r.integers(15, 60))), doc[ex:ex + 60]])
                region = (a, b)
            else:
                doc = self.free(int(r.integers(300, 1200)))
                prompt = np.concatenate([self.free(int(r.integers(15, 60))), doc])
                region = (0, len(doc))
            i, newdoc = region[0], []
            while i < region[1]:
                L = self.geo(45); seg = doc[i:min(i + L, region[1])]; emit(seg, 1); newdoc.extend(seg.tolist()); i += L
                u = r.random()
                ins = self.libseg() if u < 0.2 else self.free(self.geo(8))
                emit(ins, 2 if u < 0.2 else 0); newdoc.extend(ins.tolist()); i += self.geo(4) if r.random() < 0.6 else 0
            if self.dom == "session":   # the file evolves: next turns see the edited version
                self.session_file = np.concatenate([doc[:region[0]], np.array(newdoc, np.int32), doc[region[1]:]])
        return prompt.astype(np.int32), np.array(y, np.int32), np.array(kind, np.int8)


# toy MTP: P(draft for y[t] correct | depth d) = PC[kind_t] * DEC**(d-1); a per-token latent u_t makes the outcome
# consistent across the positions that predict the same token (hard tokens are hard for every round).
PC = {"code": (0.72, 0.93, 0.90, 0.35), "chat": (0.62, 0.90, 0.88, 0.30),
      "edit": (0.66, 0.95, 0.90, 0.35), "session": (0.66, 0.95, 0.90, 0.35)}
DEC = 0.94


def mtp_drafts(dom, y, kind, rng):
    n = len(y)
    pc = np.array(PC[dom])[kind]
    u = rng.random(n)
    tok = np.full((n, DMAX), -1, np.int32); p = np.zeros((n, DMAX), np.float32); ent = np.zeros((n, DMAX), np.float32)
    for d in range(DMAX):
        t = np.arange(n) + d
        ok_t = t < n
        tt = np.minimum(t, n - 1)
        q = pc[tt] * DEC ** d
        noise = rng.normal(0, 0.06, n)
        corr = ok_t & (u[tt] + noise < q)
        wrong = (y[tt] + 1 + rng.integers(0, V - 1, n)) % V
        tok[:, d] = np.where(corr, y[tt], wrong)
        # confidence: informative but noisy (calibrated-ish to q, shifted by correctness)
        base = np.clip(q + np.where(corr, 0.12, -0.30) + rng.normal(0, 0.12, n), 0.02, 0.995)
        p[:, d] = base
        veff = 2 + rng.gamma(2.0, 6.0, n)       # effective support of the rest of the distribution
        ent[:, d] = -(base * np.log(base)) - (1 - base) * np.log((1 - base) / veff)
    # chained drafts: after an error MTP conditions on a wrong prefix -> later drafts are not the y tokens anyway
    acc = lcp_rows(tok, y)
    return tok, p, ent, acc


def lcp_rows(tok, y):
    n, D = tok.shape
    acc = np.zeros(n, np.int32); alive = np.ones(n, bool)
    for d in range(D):
        t = np.arange(n) + d
        ok = alive & (t < n) & (tok[:, d] == y[np.minimum(t, n - 1)]) & (tok[:, d] >= 0)
        acc += ok; alive = ok
    return acc


def lcp_pair(a, b):
    n, D = a.shape
    out = np.zeros(n, np.int32); alive = np.ones(n, bool)
    for d in range(D):
        ok = alive & (a[:, d] == b[:, d]) & (a[:, d] >= 0)
        out += ok; alive = ok
    return out


def make_domain(dom, n_req, seed, session_len=8):
    """List of request dicts (SYNTHETIC). Pool = one SuffixDrafter for the whole stream (H2)."""
    g = Gen(dom, seed); rng = np.random.default_rng(seed + 1000)
    lk = NativeSuffixDrafter(3, 64, 1 << 16)
    pool = NativeSuffixDrafter(3, 64, 1 << 20)
    reqs = []
    for r in range(n_req):
        turn = r % session_len if dom == "session" else 0
        P, Y, kind = g.request(turn)
        if dom == "session" and turn == 0:
            pool.reset()                            # pool scope = one session (synthetic agentic stream)
        tok, p, ent, acc = mtp_drafts(dom, Y, kind, rng)
        lk.reset(); lk.append(P)
        lk_k, lk_m, lk_acc, lk_tok = lk.scan(Y, DMAX)
        pool.append(P)
        pl_k, pl_m, pl_acc, pl_tok = pool.scan(Y, DMAX)
        reqs.append(dict(domain=dom, req=r, session=(r // session_len) if dom == "session" else r, data_kind="synthetic",
                         n=len(Y), n_prompt=len(P), y=Y, kind=kind, mtp_tok=tok, mtp_p=p, mtp_ent=ent, mtp_acc=acc,
                         lk_k=lk_k, lk_m=lk_m, lk_acc=lk_acc, lk_tok=lk_tok, agree=lcp_pair(tok, lk_tok),
                         pl_k=pl_k, pl_m=pl_m, pl_acc=pl_acc, pl_tok=pl_tok, agree_pl=lcp_pair(tok, pl_tok)))
    return reqs
